''' Regression '''
#=================
# رگرسیون یعنی پیش‌بینی یک مقدار عددی
# درواقع رابطه بین دو چیز رو پیدا میکنه
# هر وقت خروجی مدل یک عدد باشد، داریم مسئله رگرسیون حل می‌کنیم
# رگرسیون میتونه خطی باشه یا غیر خطی




#========================
''' linear regression '''
#========================
# رگرسیون خطی یعنی فرض می‌کنیم رابطه بین ورودی و خروجی یک خط مستقیم است
# y=ax+b
# در این قسمت، باید از مدل های خطی برای پیدا کردن رابطه خط استفاده کنیم
# Lasso
# ElasticNet
# Ridge
# LinearRegressor
# SGDRegressor



#=======================
''' LinearRegression '''
#=======================
# این اسم یک مدل در scikit-learn است
# کارش پیدا کردن رابطه خطی بین دو چیز هست
# y=ax+b
# با یک روش ریاضی مستقیم بنام Least Squares برای پیدا کردن این رابطه استفاده میکنه
# یعنی اصلاً Gradient Descent استفاده نمی‌کند



#=============
''' Ridge '''
#=============
# اینم یک مدل رگراسیون خطی در scikit-learn است
# یعنی اینم میخواد رابطه خط رو پیدا کنه
# مدل Ridge همان LinearRegression است، فقط قابلیت های اضافه دارد




#===================
''' SGDRegressor '''
#===================
# باز هم همان رگرسیون خطی است یعنی باز هم می‌خواهد رابطه خط رو پیدا کند
# برعکس مدل LinearRegressor که ضرایب خط رو از روش مستقیم پیدا میکنه،
# این مدل از الگوریتم gradient descent استفاده میکنه





#=====================
''' loss function '''
#=====================
# مثلا ما یک مدل میسازیم، یک پیشبینی میکنه و این پیشبینی اشتباهه
# چقدر اشتباه کرده؟ باید این اشتباه را اندازه بگیریم

# به این مقدار اشتباه می‌گیم loss یا خطا
# و فرمولی که این خطا را حساب می‌کنه بهش میگیم Loss Function

# هر مدلی loss کمتری داشته باشه پیشبینی بهتری میکنه و مدل بهتریه
# گرادیان نزولی الگوریتمی برای محاسبه کمترین مقدار loss است




#====================================
''' MSE - RMSE - huber loss - MAE '''
#====================================

# اینا همشون معروف ترین loss function ها برای محاسبه loss در Regression هستن

# Mean Squared Error (MSE) --> most famous loss for regression
# Root Mean Squared Error (RMSE)
# Mean Absolute Error (MAE)





#============================
''' loss - learning rate '''
#============================
from sklearn.linear_model import SGDRegressor
model = SGDRegressor(loss = 'squared_error',learning_rate='constant',eta0=0.0001 , max_iter=10000,random_state=42)

# پارامتر loss مشخص میکنه خطا به چه صورت محاسبه بشه
# این loss=squared_error یعنی خطا رو با روش MSE محاسبه کن

# همچنین learning rate میشه ریتمی که باهاش کم کم برای پیدا کردن ضریب ها پیش میره




#===========================
''' nonlinear regression '''
#===========================
