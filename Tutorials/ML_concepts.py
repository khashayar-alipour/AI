#==========================
''' supervised learning '''
#==========================
# حالتی از یادگیری ماشین که هم ورودی و هم خروجی (label) رو میدیم با ماشین تا الگوهارو یاد بگیره

# براساس نوع خروجی 2 گروه میشه:
# 1-supervised regression --> خروجی بصورت پیوسته (عددی) میباشد
# 2-unsupervised classification --> خروجی بصورت دسته بندی و ناپیوسته هست



#============================
''' Unsupervised learning '''
#============================
# در دسته بندی supervised ما در ورودی یک input(x,y) داشتیم
# اینو وقتی میدادیم به مدل، هم x داشت و هم y داشت
# حالا مدل میرفت رابطه بین x و y رو پیدا میکرد
# حالا اگه y نداشته باشیم چی میشه؟

# یه چیزی داریم به اسم clustering یا خوشه کردن
# مثلا کلی عکس از سگ و گربه داریم که میدیم به یک مدل و میگیم دسته بندی کن
# یعنی ورودی x رو داریم. ولی عکسها هیچکدوم label ندارن پس y نداریم
# با اینحال مدل میاد بر اساس ویژگی های تصاویر مثل رنگ و پیکسل و ... خودش دسته بندی میکنه
# میاد میگه اینا 2 گروه هستن ولی نمیدونه یک گروه سگ هست یه گروه گربه. به این نوع دسته بندی میگن cluster کردن
# به این میگن unsupervised classification که بدون y اینکار رو انجام داد




#====================
''' Deep learning '''
#====================

# حالا اگه تعداد دیتا خیلی خیلی زیاد باشه حالتهای supervised و unsupervised جوابگو نیستن
# باید بریم سراغ الگوریتمهای پیشرفته تر که عمیق تر هستن و لایه‌ها و پارامترهای بیشتری دارن

# در ماشین لرنینگ معمولی ممکن است خودت ویژگی‌ها (Features) را استخراج کنی
# مثلا برای تشخیص گربه‌ها بگی چهارپا یا دم و ...
# ولی در DL فقط عکس رو میدی و خودش ویژگی هارو متوجه میشه

# چرا بهش میگن deep؟ چون تعداد زیادی لایه (layer) برای تشخیص داره
# برای همین بهش Deep Neural Network هم میگن




#=============================
''' Reinforcement learning '''
#=============================

# در تمام مدلهای بالا دیتای ما آماده بود و میدادیم به مدل و آنالیز میکرد
# حالا ما میخوایم مدل خودش بره توی محیط و بصورت پیوسته دیتا بگیره و آموزش ببینه
# یادگیری در این نوع، با پاداش و جزا انجام میشه و درواقع یادگیری از روی تجربه انجام میشه




