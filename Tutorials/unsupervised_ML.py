"✅ KernelPCA"
# اگر داده خطی نباشه PCA عملکرد خوبی نداره
# درواقع PCA میاد روی داده های خطی کار میکنه. روی نمودار یک محور جدید میکشه (محور قبلی رو میچرخونه)
# سپس دیتاهارو روی این محور جدید تصویر میکنه
# Height                   Height
# │     /                    |  \ 
# │    /                     |   \
# │   /          PCA ->      |    \
# │  /                       |     \
# │ /                        |      \
# └─────── Weight            └─────────── Weight
  # محور جدید               محور قدیم   

# درواقع kernelPCA نسخه پیشرفته‌تر PCA است که برای داده‌های غیرخطی (Nonlinear) ساخته شده است
# اگر نمودار داده ها غیر خطی (مثلا منحنی) باشه PCA دیگه کارایی نداره چون فقط دنبال خط راست میگرده
# ایده اصلی Kernel PCA اینه که میگه اگر داده‌ها در این فضا خطی نیستند، بیایید آن‌ها را به فضای دیگری ببریم که در آن خطی شوند

# فرض کنیم داده ها روی یک دایره رسم شده اند
# اینجا PCA فقط یک خط میبینه ولی Kernel PCA دایره رو به یک فضای جدید میبره
# در اون فضای جدید دایره تقریبا تبدیل به یک خط میشه سپس PCA روش اجرا میشه
#      ●  ●
#    ●      ●
#   ●        ●
#    ●      ●
#      ●  ●

#     PCA                   Kernel PCA
# --------------        ----------------
# Original Data           Original Data
#       ↓                         ↓
# Rotate Axes             Kernel Function
#       ↓                         ↓
# Reduce Dimension        Higher-dimensional Space
#                                 ↓   
#                                PCA               
#                                 ↓
#                         Reduce Dimension          

