#===== SKlearn =====
from sklearn.datasets import make_blobs
from sklearn.cluster import KMeans
import matplotlib.pyplot as plt

x,y = make_blobs(n_samples=300, centers=3, random_state=42)

# اینجا مقادیر 1 تا 10 برای K رو بوسیله حلقه میدیم به مدل تا بهترین مقدار مشخص بشه
wcss = []   # [1000, 620, 260, 220, 210, 205, 203, 202, 201, 200]
for k in range(1,11):
    model = KMeans(n_clusters=k, random_state=42 )
    model.fit(x)
    wcss.append(model.inertia_)

# رسم نمودار Elbow
# 👨 با نگاه کردن به نمودار تصمیم میگیریم بهترین مقدار برای k چی هست
plt.plot(range(1,11), wcss, marker="o")
plt.xlabel("Number of Clusters (K)")
plt.ylabel("WCSS (Inertia)")
plt.title("Elbow Method")
plt.grid(True)
plt.show()

# حالا که بهترین مقدار k مشخص شد دوباره مدل رو میسازیم
