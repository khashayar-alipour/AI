from sklearn.datasets import make_blobs
from sklearn.cluster import KMeans
import matplotlib.pyplot as plt

x,y = make_blobs(n_samples=300, centers=3, random_state=42)

plt.scatter(x[:,0], x[:,1] )
plt.xlabel("Feature 1")
plt.ylabel("Feature 2")
plt.title("Scatter plot of features")
plt.show()

model = KMeans(n_clusters=3, random_state=42)
model.fit(x)

y_pred = model.labels_
print(y_pred[0:10])    # [1 1 0 2 1 2 0 2 0 0]

model.cluster_centers_
# [[-2.63323268,  9.04356978],
#  [-6.88387179, -6.98398415],
#  [ 4.74710337,  2.01059427]]

new_points = [[2,5]]
model.predict(new_points)   # array([2], dtype=int32)    خوشه شماره 2

# رسم نقاط center که توسط مدل انتخاب شدن
plt.scatter(x[:,0], x[:,1], c=y_pred)
plt.scatter(model.cluster_centers_[:,0], model.cluster_centers_[:,1], s=200, c="red", marker="x")
plt.show()
